//! canon — what a book is, before any text of it exists.
//!
//! ```text
//! canon::book(MAT)                 -> Book { usfm_number: "41", canonical_index: Some(40), .. }
//! canon::parse_book("1samuel")     -> Some(1SA)    code, slug, English name or alias; folded
//! canon::books(Canon::Protestant66) -> GEN .. REV  in canonical order
//! canon::usfm_file_name(MAT)       -> "41-MAT.usfm"
//! canon::name(MAT, &["fr"], Long)  -> Named { text: "Matthieu", locale: "fr", form: Long }
//! canon::parse_book_in("Éxodo", &["es"]) -> Some(EXO)   a gateway language's names; accents fold
//!
//! canon::scheme("eng")?.chapters(MAL)       -> Some(4)   org says 3
//! canon::scheme("ulb")?.last_verse(ACT, 19) -> Some(40)  eng says 41
//!
//! canon::map(eng, org, GEN 31:55)           -> Moved(GEN 32:1)
//! canon::map(org, eng, PSA 13:6)            -> Split([PSA 13:5, PSA 13:6])
//! canon::pairs(ulb, org, PSA)               -> [PSA 3:0] ↔ [PSA 3:1], [PSA 3:1] ↔ [PSA 3:2], …
//! ```
//!
//! The data is `data/books.tsv`, one row per USFM book identifier, and
//! `data/schemes/*.json`, one file per versification scheme. The tables the
//! code reads (`src/tables.rs` and `src/scheme_tables.rs`, with `ts/` twins
//! for the TypeScript side) are generated by `cargo run -p canon-gen`, whose
//! test fails when any is stale. Nothing is parsed at run time.
//!
//! canon::sniff(&inventory)                  -> ulb, Decided, on 250 votes (en_ulb)
//!
//! Coverage (a text against its scheme) is onion's `lint_against_counts`,
//! given a scheme's counts; galley wires them. The plan was
//! `planning/items/2026-11-04-canon-and-versification-the-book-table-schemes-map.mdx`.

